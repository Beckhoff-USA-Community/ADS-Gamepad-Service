///<AutoGeneratedContent id="ImplementationOf_ITcCyclic">
HRESULT CGamepad::CycleUpdate(ITcTask* ipTask, ITcUnknown* ipCaller, ULONG_PTR context)
{
	// age of the gamepad data in task cycles, saturating counter
	if (m_Outputs.nDataAgeCycles < 0xFFFFFFFFUL)
		m_Outputs.nDataAgeCycles++;

	// the extended block has its own age. It climbs forever while extended
	// reads are off or failing, so it never lies fresh
	if (m_ExtOutputs.nExtDataAgeCycles < 0xFFFFFFFFUL)
		m_ExtOutputs.nExtDataAgeCycles++;

	const ULONG timeoutLimit = (m_TimeoutCycles != 0) ? m_TimeoutCycles : s_GamepadTimeoutDefault;

	switch (m_Phase)
	{
	case Phase_Idle:
	{
		if (FAILED(AcquireAdsInvoker(ipTask)))
		{
			FailSafe(GamepadComm_NoTask);
			break;
		}

		if (m_bNeedResolve && !m_bResolved)
		{
			// the configured Net ID means the local system, probe the
			// candidate addresses until one reaches the service
			m_ResolveIndex = 0;
			m_Phase = Phase_Resolve;
			break;
		}

		// one time read of the service info block, contract v1.1. Older
		// services answer with an error, that is fine, the block stays zero
		if (SUCCEEDED(IssueRead(s_GamepadInfoGroup, 0, s_GamepadInfoLength)))
		{
			m_Phase = Phase_InfoRead;
		}
		else
		{
			memset(&m_Outputs.stServiceInfo, 0, sizeof(m_Outputs.stServiceInfo));
			m_Phase = Phase_Run;
		}
		break;
	}

	case Phase_Resolve:
	{
		if (m_bRequestInFlight)
		{
			ULONG adsResult = 0;
			ULONG cbData = 0;
			PVOID pData = NULL;
			HRESULT hr = m_spAdsInvoker->GetAdsCon(m_AdsStamp, &adsResult, &cbData, &pData);
			if (hr == ADS_E_PENDING)
			{
				if (++m_CyclesInFlight >= s_GamepadResolveProbeCycles)
				{
					m_Trace.Log(tlVerbose, FNAMEA_STRV("candidate %u.%u.%u.%u.%u.%u did not answer",
						m_ServiceAddr.netId.b[0], m_ServiceAddr.netId.b[1], m_ServiceAddr.netId.b[2],
						m_ServiceAddr.netId.b[3], m_ServiceAddr.netId.b[4], m_ServiceAddr.netId.b[5]));
					DropRequest();
					AdvanceResolve();
				}
				break;
			}

			if (FAILED(hr))
			{
				// no answer was fetched, the invoker itself failed
				DropRequest();
				AdvanceResolve();
				break;
			}

			// an answer arrived. Success and ADS error both prove that the
			// candidate address delivers requests to the service port, so
			// it is locked in for all further traffic
			m_bResolved = true;
			if (adsResult == 0 && pData != NULL && cbData == s_GamepadInfoLength)
			{
				// the wire block is 32 bytes, the module keeps the first 16,
				// the rest is reserved and zero today
				memcpy(&m_Outputs.stServiceInfo, pData, sizeof(m_Outputs.stServiceInfo));
			}
			else
			{
				memset(&m_Outputs.stServiceInfo, 0, sizeof(m_Outputs.stServiceInfo));
			}
			DropRequest();
			m_Trace.Log(tlInfo, FNAMEA_STRV("service address locked to %u.%u.%u.%u.%u.%u",
				m_ServiceAddr.netId.b[0], m_ServiceAddr.netId.b[1], m_ServiceAddr.netId.b[2],
				m_ServiceAddr.netId.b[3], m_ServiceAddr.netId.b[4], m_ServiceAddr.netId.b[5]));
			m_Phase = Phase_Run;
			break;
		}

		// no probe in flight, send one to the current candidate
		m_ServiceAddr.netId = m_ResolveCandidates[m_ResolveIndex];
		if (FAILED(IssueRead(s_GamepadInfoGroup, 0, s_GamepadInfoLength)))
		{
			AdvanceResolve();
		}
		break;
	}

	case Phase_InfoRead:
	{
		ULONG adsResult = 0;
		ULONG cbData = 0;
		PVOID pData = NULL;
		HRESULT hr = m_spAdsInvoker->GetAdsCon(m_AdsStamp, &adsResult, &cbData, &pData);
		if (hr == ADS_E_PENDING)
		{
			if (++m_CyclesInFlight >= timeoutLimit)
			{
				m_Trace.Log(tlWarning, FNAMEA_STRV("service info read timed out after %u cycles, continuing without it", m_CyclesInFlight));
				DropRequest();
				memset(&m_Outputs.stServiceInfo, 0, sizeof(m_Outputs.stServiceInfo));
				m_Phase = Phase_Run;
			}
			break;
		}

		if (SUCCEEDED(hr))
			hr = MAKE_ADS_HRESULT(adsResult);

		if (SUCCEEDED(hr) && pData != NULL && cbData == s_GamepadInfoLength)
		{
			// the wire block is 32 bytes, the module keeps the first 16,
			// the rest is reserved and zero today
			memcpy(&m_Outputs.stServiceInfo, pData, sizeof(m_Outputs.stServiceInfo));
		}
		else
		{
			memset(&m_Outputs.stServiceInfo, 0, sizeof(m_Outputs.stServiceInfo));
		}
		DropRequest();
		m_Phase = Phase_Run;
		break;
	}

	case Phase_Run:
	{
		if (m_bRequestInFlight)
		{
			ULONG adsResult = 0;
			ULONG cbData = 0;
			PVOID pData = NULL;
			HRESULT hr = m_spAdsInvoker->GetAdsCon(m_AdsStamp, &adsResult, &cbData, &pData);
			if (hr == ADS_E_PENDING)
			{
				if (++m_CyclesInFlight >= timeoutLimit)
				{
					if (m_bWriteInFlight)
						m_bForceReadNext = true;
					// no answer at all proves the service stopped talking,
					// whichever block was asked for. Only an answered
					// extended read error stays isolated; a silent one fails
					// safe like every other timeout, so enabling the extended
					// block never widens the fail safe reaction bound
					DropRequest();
					m_Outputs.nErrorCount++;
					FailSafe(GamepadComm_Timeout);
				}
				break;
			}

			const bool bWasWrite = m_bWriteInFlight;
			const bool bWasExt = m_bExtInFlight;
			if (SUCCEEDED(hr))
				hr = MAKE_ADS_HRESULT(adsResult);

			if (SUCCEEDED(hr) && bWasWrite)
			{
				DropRequest();
				m_RumbleSent[0] = m_RumbleTx[0];
				m_RumbleSent[1] = m_RumbleTx[1];
				m_bRumbleSentValid = true;
			}
			else if (SUCCEEDED(hr) && bWasExt && pData != NULL && cbData == s_GamepadExtReadLength)
			{
				// answer buffer belongs to the invoker, copy before release
				memcpy(&m_ExtWireData, pData, sizeof(m_ExtWireData));
				DropRequest();
				DecodeExtOutputs();
				m_ExtOutputs.nExtDataAgeCycles = 0;
			}
			else if (SUCCEEDED(hr) && !bWasExt && pData != NULL && cbData == s_GamepadReadLength)
			{
				// answer buffer belongs to the invoker, copy before release
				memcpy(&m_WireData, pData, sizeof(m_WireData));
				DropRequest();
				DecodeOutputs();
				m_Outputs.nDataAgeCycles = 0;
				SetCommState(GamepadComm_Ok);
			}
			else if (bWasExt)
			{
				// an extended read error or short answer zeroes only the
				// extended outputs. The gamepad exchange keeps running and
				// keeps owning the comm state
				DropRequest();
				m_Outputs.nErrorCount++;
				ZeroExtOutputs();
			}
			else
			{
				// covers ADS errors and short answers, fail safe either way.
				// a failed rumble write yields one read before the retry so
				// the gamepad data stays alive
				if (bWasWrite)
					m_bForceReadNext = true;
				DropRequest();
				m_Outputs.nErrorCount++;
				FailSafe(GamepadComm_AdsError);
			}
		}

		if (!m_bRequestInFlight)
		{
			const ULONG idxGrp = static_cast<ULONG>(m_ControllerNumber) << 16;

			bool bWrite = false;
			if (m_Inputs.bRumbleEnable && !m_bForceReadNext)
			{
				bWrite = !m_bRumbleSentValid
					|| m_Inputs.fRumbleLeft != m_RumbleSent[0]
					|| m_Inputs.fRumbleRight != m_RumbleSent[1];
			}
			// a forced slot always carries the gamepad read, so live data
			// returns after one round trip even when the extended turn is
			// pending; the extended read simply waits one more cycle
			const bool bForcedRead = m_bForceReadNext;
			m_bForceReadNext = false;

			HRESULT hr;
			bool bExtRead = false;
			if (bWrite)
			{
				// payload must stay stable while the write is in flight
				m_RumbleTx[0] = m_Inputs.fRumbleLeft;
				m_RumbleTx[1] = m_Inputs.fRumbleRight;
				hr = IssueWrite(idxGrp, s_GamepadRumbleOffset, s_GamepadRumbleLength, m_RumbleTx);
			}
			else if (!bForcedRead && ExtReadEnabled() && m_bExtReadTurn)
			{
				// reads alternate between the gamepad block and the extended
				// block, so each runs at half the task rate
				bExtRead = true;
				m_bExtReadTurn = false;
				hr = IssueRead(idxGrp + s_GamepadExtGroupOffset, 0, s_GamepadExtReadLength);
			}
			else
			{
				m_bExtReadTurn = ExtReadEnabled();
				hr = IssueRead(idxGrp, 0, s_GamepadReadLength);
			}

			if (FAILED(hr))
			{
				m_Outputs.nErrorCount++;
				if (bExtRead)
					ZeroExtOutputs();
				else
					FailSafe(GamepadComm_AdsError);
			}
			else if (bExtRead)
			{
				m_bExtInFlight = true;
			}
		}
		break;
	}

	default:
		m_Phase = Phase_Idle;
		break;
	}

	return S_OK;
}
