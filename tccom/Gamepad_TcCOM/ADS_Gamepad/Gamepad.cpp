///////////////////////////////////////////////////////////////////////////////
// Register the module for cyclic execution with the task named by the
// CyclicCaller interface pointer. Without a valid task OID the transition
// to OP fails on purpose, an unwired module would never be called
HRESULT CGamepad::AddModuleToCaller()
{
	m_Trace.Log(tlVerbose, FENTERA_STR());

	HRESULT hr = S_OK;
	if ( m_spCyclicCaller.HasOID() )
	{
		if ( SUCCEEDED_DBG(hr = m_spSrv->TcQuerySmartObjectInterface(m_spCyclicCaller)) )
		{
			if ( FAILED(hr = m_spCyclicCaller->AddModule(m_spCyclicCaller, THIS_CAST(ITcCyclic))) )
			{
				m_spCyclicCaller = NULL;
			}
		}
	}
	else
	{
		hr = ADS_E_INVALIDOBJID;
		SUCCEEDED_DBGT(hr, "Invalid OID specified for caller task");
	}

	m_Trace.Log(tlVerbose, FLEAVEA_STRV("hr=0x%08x", hr));
	return hr;
}

///////////////////////////////////////////////////////////////////////////////
VOID CGamepad::RemoveModuleFromCaller()
{
	m_Trace.Log(tlVerbose, FENTERA_STR());

	if ( m_spCyclicCaller )
	{
		m_spCyclicCaller->RemoveModule(m_spCyclicCaller);
	}
	m_spCyclicCaller = NULL;

	m_Trace.Log(tlVerbose, FLEAVEA_STR());
}

///////////////////////////////////////////////////////////////////////////////
// Ask the router object for the local AMS Net ID. On this platform ADS
// requests from the task port to the loopback Net ID are not answered, so
// the real local Net ID is the best candidate for local resolution.
void CGamepad::QueryLocalNetId()
{
	m_bLocalNetIdValid = false;
	memset(&m_LocalNetId, 0, sizeof(m_LocalNetId));

	ITComRouterPtr spRouter;
	HRESULT hr = m_spSrv->TcQueryObjectInterface(OID_TCROUTER_CTRL, spRouter.GetIID(), reinterpret_cast<PPVOID>(&spRouter));
	if (FAILED(hr) || !spRouter)
	{
		m_Trace.Log(tlVerbose, FNAMEA_STRV("router object not available, hr=0x%08x", hr));
		return;
	}

	AmsNetId netId;
	memset(&netId, 0, sizeof(netId));
	spRouter->GetLocalNetId(netId);

	bool bAllZero = true;
	for (int i = 0; i < 6; i++)
	{
		if (netId.b[i] != 0)
			bAllZero = false;
	}
	if (bAllZero || memcmp(&netId, &AMSNETID_LOOPBACK, sizeof(netId)) == 0)
	{
		m_Trace.Log(tlVerbose, FNAMEA_STRN("router reported no usable local Net ID"));
		return;
	}

	m_LocalNetId = netId;
	m_bLocalNetIdValid = true;
	m_Trace.Log(tlInfo, FNAMEA_STRV("router reports local Net ID %u.%u.%u.%u.%u.%u",
		netId.b[0], netId.b[1], netId.b[2], netId.b[3], netId.b[4], netId.b[5]));
}

///////////////////////////////////////////////////////////////////////////////
// Build the target address from the ServiceAmsNetId parameter. All zeros
// and the loopback Net ID both mean the local system. In that case the
// state machine probes candidate addresses until one answers, because the
// loopback Net ID is not reliably routed from the task port.
void CGamepad::ResolveServiceAddr()
{
	m_ServiceAddr.port = s_GamepadServicePort;

	bool bAllZero = true;
	for (int i = 0; i < 6; i++)
	{
		if (m_ServiceAmsNetId.b[i] != 0)
			bAllZero = false;
	}
	const bool bLoopback = memcmp(&m_ServiceAmsNetId, &AMSNETID_LOOPBACK, sizeof(m_ServiceAmsNetId)) == 0;

	m_bNeedResolve = bAllZero || bLoopback;
	m_bResolved = false;
	m_ResolveCandidateCount = 0;
	m_ResolveIndex = 0;

	if (!m_bNeedResolve)
	{
		// a real Net ID is configured, use it directly
		m_ServiceAddr.netId = m_ServiceAmsNetId;
		return;
	}

	// candidate order: the router supplied local Net ID first, then the
	// all zero address, then loopback. The first candidate that answers
	// the info block read is locked in for all further traffic.
	if (m_bLocalNetIdValid)
		m_ResolveCandidates[m_ResolveCandidateCount++] = m_LocalNetId;
	AmsNetId zeroNetId;
	memset(&zeroNetId, 0, sizeof(zeroNetId));
	m_ResolveCandidates[m_ResolveCandidateCount++] = zeroNetId;
	m_ResolveCandidates[m_ResolveCandidateCount++] = AMSNETID_LOOPBACK;
	m_ServiceAddr.netId = m_ResolveCandidates[0];
}

///////////////////////////////////////////////////////////////////////////////
// Move on to the next candidate address. When the whole list failed the
// timeout is published once and probing starts over, the module never
// gives up on finding the service.
void CGamepad::AdvanceResolve()
{
	m_ResolveIndex++;
	if (m_ResolveIndex >= m_ResolveCandidateCount)
	{
		m_ResolveIndex = 0;
		m_Outputs.nErrorCount++;
		FailSafe(GamepadComm_Timeout);
	}
}

///////////////////////////////////////////////////////////////////////////////
// Resolve the ADS invoker of the task that drives this module and create
// the request stamp. Preferred source is the CyclicCaller interface pointer,
// the calling task itself is the fallback.
HRESULT CGamepad::AcquireAdsInvoker(ITcTask* ipTask)
{
	if (m_spAdsInvoker && m_bStampCreated)
		return S_OK;

	if (!m_spAdsInvoker && m_spCyclicCaller.HasOID())
	{
		m_spSrv->TcQueryObjectInterface(m_spCyclicCaller.GetOID(), m_spAdsInvoker.GetIID(), reinterpret_cast<PPVOID>(&m_spAdsInvoker));
	}
	if (!m_spAdsInvoker && ipTask != NULL)
	{
		ipTask->TcQueryInterface(m_spAdsInvoker.GetIID(), reinterpret_cast<PPVOID>(&m_spAdsInvoker));
	}
	if (!m_spAdsInvoker)
		return ADS_E_INVALIDOBJID;

	HRESULT hr = m_spAdsInvoker->CreateStamp(m_AdsStamp);
	if (FAILED(hr))
	{
		m_Trace.Log(tlError, FNAMEA_STRV("CreateStamp failed, hr=0x%08x", hr));
		m_spAdsInvoker = NULL;
		return hr;
	}
	m_bStampCreated = true;
	return S_OK;
}

///////////////////////////////////////////////////////////////////////////////
void CGamepad::ReleaseAdsInvoker()
{
	m_spAdsInvoker = NULL;
	m_bStampCreated = false;
	m_Phase = Phase_Idle;
}

///////////////////////////////////////////////////////////////////////////////
// Start an ADS read on the task port. The invoker owns the answer buffer,
// it is fetched and copied on completion.
HRESULT CGamepad::IssueRead(ULONG idxGrp, ULONG idxOffs, ULONG cbLength)
{
	if (!m_spAdsInvoker || !m_bStampCreated || m_bRequestInFlight)
		return ADS_E_INVALIDSTATE;

	m_AdsCnt++;
	HRESULT hr = m_spAdsInvoker->ReadReqInv(m_AdsStamp, m_AdsCnt, m_ServiceAddr, idxGrp, idxOffs, cbLength, NULL);
	if (FAILED(hr))
		return hr;

	m_bRequestInFlight = true;
	m_bWriteInFlight = false;
	m_CyclesInFlight = 0;
	return S_OK;
}

///////////////////////////////////////////////////////////////////////////////
// Start an ADS write on the task port. pData must stay valid until the
// answer arrives, callers pass a member buffer.
HRESULT CGamepad::IssueWrite(ULONG idxGrp, ULONG idxOffs, ULONG cbLength, PVOID pData)
{
	if (!m_spAdsInvoker || !m_bStampCreated || m_bRequestInFlight)
		return ADS_E_INVALIDSTATE;

	m_AdsCnt++;
	HRESULT hr = m_spAdsInvoker->WriteReqInv(m_AdsStamp, m_AdsCnt, m_ServiceAddr, idxGrp, idxOffs, cbLength, pData);
	if (FAILED(hr))
		return hr;

	m_bRequestInFlight = true;
	m_bWriteInFlight = true;
	m_CyclesInFlight = 0;
	return S_OK;
}

///////////////////////////////////////////////////////////////////////////////
// Remove the pending request context from the invoker and clear the in
// flight bookkeeping. Safe to call without a pending request.
void CGamepad::DropRequest()
{
	if (m_bRequestInFlight && m_spAdsInvoker)
		m_spAdsInvoker->RemoveAdsCon(m_AdsStamp);
	m_bRequestInFlight = false;
	m_bWriteInFlight = false;
	m_bExtInFlight = false;
	m_CyclesInFlight = 0;
}

///////////////////////////////////////////////////////////////////////////////
void CGamepad::SetCommState(ULONG state)
{
	if (m_Outputs.eCommState != state)
	{
		m_Trace.Log(tlInfo, FNAMEA_STRV("comm state changed from %u to %u", m_Outputs.eCommState, state));
		m_Outputs.eCommState = state;
	}
}

///////////////////////////////////////////////////////////////////////////////
// Zero the decoded gamepad outputs and publish the new comm state. The
// consumer sees a disconnected gamepad with centered sticks, so every
// error path funnels through here. The extended outputs are zeroed too,
// stale motion or touch data must not outlive the gamepad data.
void CGamepad::FailSafe(ULONG state)
{
	ZeroDecodedOutputs();
	ZeroExtOutputs();
	SetCommState(state);
}

///////////////////////////////////////////////////////////////////////////////
// Zero everything decoded from the wire block. The diagnostic counters and
// the service info block stay untouched, they describe the communication,
// not the gamepad.
void CGamepad::ZeroDecodedOutputs()
{
	m_Outputs.bConnected = false;
	m_Outputs.nReserved1 = 0;
	m_Outputs.nReserved2 = 0;
	m_Outputs.nReserved3 = 0;
	memset(&m_Outputs.stButtons, 0, sizeof(m_Outputs.stButtons));
	m_Outputs.fLeftStickX = 0.0f;
	m_Outputs.fLeftStickY = 0.0f;
	m_Outputs.fRightStickX = 0.0f;
	m_Outputs.fRightStickY = 0.0f;
	m_Outputs.fLeftTrigger = 0.0f;
	m_Outputs.fRightTrigger = 0.0f;
	m_Outputs.nButtonsRaw = 0;
	m_Outputs.nStatesRaw = 0;
}

///////////////////////////////////////////////////////////////////////////////
// Apply deadzone and curve to one axis or trigger value. The deadzone is
// rescaled away so motion starts smoothly at the deadzone edge, the curve
// is an exponent on the remaining 0 to 1 magnitude. Sign is preserved.
float CGamepad::ShapeValue(float value, float deadzonePercent, float curve)
{
	float deadzone = deadzonePercent;
	if (deadzone < 0.0f)
		deadzone = 0.0f;
	if (deadzone > s_GamepadDeadzoneMax)
		deadzone = s_GamepadDeadzoneMax;

	float exponent = curve;
	if (exponent < s_GamepadCurveMin)
		exponent = s_GamepadCurveMin;
	if (exponent > s_GamepadCurveMax)
		exponent = s_GamepadCurveMax;

	float magnitude = (value < 0.0f) ? -value : value;
	if (magnitude <= deadzone)
		return 0.0f;
	if (magnitude > 100.0f)
		magnitude = 100.0f;

	float unit = (magnitude - deadzone) / (100.0f - deadzone);
	if (exponent != 1.0f)
		unit = powf_(unit, exponent);

	const float shaped = unit * 100.0f;
	return (value < 0.0f) ? -shaped : shaped;
}

///////////////////////////////////////////////////////////////////////////////
// Decode the raw wire block into the output data area. Runs once per
// successful read. Online parameter writes are serialized against
// CycleUpdate by the object lock, so the tuning values are stable here.
void CGamepad::DecodeOutputs()
{
	const SHORT buttons = m_WireData.nButtons;

	m_Outputs.bConnected = (m_WireData.nStates & 0x0001) != 0;
	m_Outputs.stButtons.bDPadUp = (buttons & 0x0001) != 0;
	m_Outputs.stButtons.bDPadDown = (buttons & 0x0002) != 0;
	m_Outputs.stButtons.bDPadLeft = (buttons & 0x0004) != 0;
	m_Outputs.stButtons.bDPadRight = (buttons & 0x0008) != 0;
	m_Outputs.stButtons.bStart = (buttons & 0x0010) != 0;
	m_Outputs.stButtons.bBack = (buttons & 0x0020) != 0;
	m_Outputs.stButtons.bLeftThumb = (buttons & 0x0040) != 0;
	m_Outputs.stButtons.bRightThumb = (buttons & 0x0080) != 0;
	m_Outputs.stButtons.bLeftShoulder = (buttons & 0x0100) != 0;
	m_Outputs.stButtons.bRightShoulder = (buttons & 0x0200) != 0;
	m_Outputs.stButtons.bA = (buttons & 0x1000) != 0;
	m_Outputs.stButtons.bB = (buttons & 0x2000) != 0;
	m_Outputs.stButtons.bX = (buttons & 0x4000) != 0;
	m_Outputs.stButtons.bY = (buttons & 0x8000) != 0;

	m_Outputs.fLeftStickX = ShapeValue(m_WireData.fLeftStickX, m_OnlineStickDeadzonePercent, m_OnlineStickCurve);
	m_Outputs.fLeftStickY = ShapeValue(m_WireData.fLeftStickY, m_OnlineStickDeadzonePercent, m_OnlineStickCurve);
	m_Outputs.fRightStickX = ShapeValue(m_WireData.fRightStickX, m_OnlineStickDeadzonePercent, m_OnlineStickCurve);
	m_Outputs.fRightStickY = ShapeValue(m_WireData.fRightStickY, m_OnlineStickDeadzonePercent, m_OnlineStickCurve);
	m_Outputs.fLeftTrigger = ShapeValue(m_WireData.fLeftTrigger, m_OnlineTriggerDeadzonePercent, m_OnlineTriggerCurve);
	m_Outputs.fRightTrigger = ShapeValue(m_WireData.fRightTrigger, m_OnlineTriggerDeadzonePercent, m_OnlineTriggerCurve);

	m_Outputs.nButtonsRaw = m_WireData.nButtons;
	m_Outputs.nStatesRaw = m_WireData.nStates;
}

///////////////////////////////////////////////////////////////////////////////
// Extended reads run only when the parameter asks for them and the service
// info block announces the extended block in its capabilities. The info
// block is read once at start, so a service upgraded while the module runs
// is picked up at the next restart. If the one time info read failed the
// extended reads stay off, which errs on the quiet side.
bool CGamepad::ExtReadEnabled() const
{
	if (!m_bReadExtended)
		return false;
	return (m_Outputs.stServiceInfo.dwCapabilities & GAMEPAD_CAPABILITY_EXT_BLOCK) != 0;
}

///////////////////////////////////////////////////////////////////////////////
// Decode the raw extended block into its output data area. Runs once per
// successful extended read. The present flag comes from the service, a
// slot without extended data serves all zero with the flag clear.
void CGamepad::DecodeExtOutputs()
{
	m_ExtOutputs.bExtDataPresent = (m_ExtWireData.nExtFlags & GAMEPAD_EXTFLAG_DATA_PRESENT) != 0;
	m_ExtOutputs.bPS = (m_ExtWireData.nExtButtons & GAMEPAD_EXTBUTTON_PS) != 0;
	m_ExtOutputs.bMute = (m_ExtWireData.nExtButtons & GAMEPAD_EXTBUTTON_MUTE) != 0;
	m_ExtOutputs.bTouchpadClick = (m_ExtWireData.nExtButtons & GAMEPAD_EXTBUTTON_TOUCHPAD_CLICK) != 0;
	m_ExtOutputs.nGyroX = m_ExtWireData.nGyroX;
	m_ExtOutputs.nGyroY = m_ExtWireData.nGyroY;
	m_ExtOutputs.nGyroZ = m_ExtWireData.nGyroZ;
	m_ExtOutputs.nAccelX = m_ExtWireData.nAccelX;
	m_ExtOutputs.nAccelY = m_ExtWireData.nAccelY;
	m_ExtOutputs.nAccelZ = m_ExtWireData.nAccelZ;
	m_ExtOutputs.stTouch0.bActive = m_ExtWireData.nTouch0Active != 0;
	m_ExtOutputs.stTouch0.nContactId = m_ExtWireData.nTouch0ContactId;
	m_ExtOutputs.stTouch0.nX = m_ExtWireData.nTouch0X;
	m_ExtOutputs.stTouch0.nY = m_ExtWireData.nTouch0Y;
	m_ExtOutputs.stTouch1.bActive = m_ExtWireData.nTouch1Active != 0;
	m_ExtOutputs.stTouch1.nContactId = m_ExtWireData.nTouch1ContactId;
	m_ExtOutputs.stTouch1.nX = m_ExtWireData.nTouch1X;
	m_ExtOutputs.stTouch1.nY = m_ExtWireData.nTouch1Y;
	m_ExtOutputs.nSequence = m_ExtWireData.nSequence;
	m_ExtOutputs.bBatteryValid = (m_ExtWireData.nExtFlags & GAMEPAD_EXTFLAG_BATTERY_VALID) != 0;
	m_ExtOutputs.nBatteryPercent = m_ExtWireData.nBatteryPercent;
	m_ExtOutputs.bBatteryCharging = (m_ExtWireData.nBatteryFlags & GAMEPAD_BATTERYFLAG_CHARGING) != 0;
	m_ExtOutputs.bBatteryFull = (m_ExtWireData.nBatteryFlags & GAMEPAD_BATTERYFLAG_FULL) != 0;
}

///////////////////////////////////////////////////////////////////////////////
// Zero everything decoded from the extended block. The age counter stays
// untouched on purpose, it keeps climbing and tells the consumer how old
// the last good extended data is.
void CGamepad::ZeroExtOutputs()
{
	m_ExtOutputs.bExtDataPresent = false;
	m_ExtOutputs.bPS = false;
	m_ExtOutputs.bMute = false;
	m_ExtOutputs.bTouchpadClick = false;
	m_ExtOutputs.nGyroX = 0;
	m_ExtOutputs.nGyroY = 0;
	m_ExtOutputs.nGyroZ = 0;
	m_ExtOutputs.nAccelX = 0;
	m_ExtOutputs.nAccelY = 0;
	m_ExtOutputs.nAccelZ = 0;
	memset(&m_ExtOutputs.stTouch0, 0, sizeof(m_ExtOutputs.stTouch0));
	memset(&m_ExtOutputs.stTouch1, 0, sizeof(m_ExtOutputs.stTouch1));
	m_ExtOutputs.nSequence = 0;
	m_ExtOutputs.nBatteryPercent = 0;
	m_ExtOutputs.bBatteryCharging = false;
	m_ExtOutputs.bBatteryFull = false;
	m_ExtOutputs.bBatteryValid = false;
}
