///////////////////////////////////////////////////////////////////////////////
// State transition from SAFEOP to OP
//
// Register with other TwinCAT objects
HRESULT CGamepad::SetObjStateSO()
{
	m_Trace.Log(tlVerbose, FENTERA_STR());
	HRESULT hr = S_OK;

	if (SUCCEEDED(hr))
	{
		// fail safe start values, all zero means no gamepad data yet
		memset(&m_Outputs, 0, sizeof(m_Outputs));
		memset(&m_ExtOutputs, 0, sizeof(m_ExtOutputs));
		m_bExtInFlight = false;
		m_bExtReadTurn = false;

		// seed the live tuning values from the init parameters. The init set
		// is stored in the project, the online set is what the shaping uses
		// and what the Parameter (Online) tab adjusts at runtime
		m_OnlineStickDeadzonePercent = m_StickDeadzonePercent;
		m_OnlineStickCurve = m_StickCurve;
		m_OnlineTriggerDeadzonePercent = m_TriggerDeadzonePercent;
		m_OnlineTriggerCurve = m_TriggerCurve;

		QueryLocalNetId();
		ResolveServiceAddr();

		// the task ADS invoker is resolved here when the CyclicCaller
		// interface pointer is wired, otherwise the first cycle retries
		// through the calling task itself
		AcquireAdsInvoker(NULL);

		m_Phase = Phase_Idle;
		m_bRequestInFlight = false;
		m_bWriteInFlight = false;
		m_bForceReadNext = false;
		m_CyclesInFlight = 0;
		m_bRumbleSentValid = false;
	}

	// If the following call succeeds the CycleUpdate method will be called,
	// possibly even before the method has been left
	hr = FAILED(hr) ? hr : AddModuleToCaller();

	// Cleanup if transition failed at some stage
	if ( FAILED(hr) )
	{
		SetObjStateOS();
	}

	m_Trace.Log(tlVerbose, FLEAVEA_STRV("hr=0x%08x", hr));
	return hr;
}

///////////////////////////////////////////////////////////////////////////////
// State transition from OP to SAFEOP
HRESULT CGamepad::SetObjStateOS()
{
	m_Trace.Log(tlVerbose, FENTERA_STR());

	HRESULT hr = S_OK;

	RemoveModuleFromCaller();
	DropRequest();
	ReleaseAdsInvoker();

	m_Trace.Log(tlVerbose, FLEAVEA_STRV("hr=0x%08x", hr));
	return hr;
}

